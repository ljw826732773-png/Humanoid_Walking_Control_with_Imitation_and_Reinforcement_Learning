import argparse
import csv
import os


ARTIFACTS = [
    ("Final demo video", "portfolio_retrain_bc_improved/bc_improved_demo.mp4"),
    ("Keyframe overview", "portfolio_retrain_bc_improved/keyframes/bc_improved_keyframes.png"),
    ("Main evaluation CSV", "portfolio_retrain_bc_improved/bc_improved_eval.csv"),
    ("Main summary CSV", "portfolio_retrain_bc_improved/bc_improved_summary.csv"),
    ("Training log", "portfolio_retrain_bc_improved/bc_improved_training_log.csv"),
    ("Rollout selection log", "portfolio_retrain_bc_improved/bc_improved_rollout_selection.csv"),
    ("Stability diagnostics", "portfolio_retrain_bc_improved/stability_diagnostics.csv"),
    ("Robustness sweep", "portfolio_retrain_bc_improved/robustness_sweep.csv"),
    ("Artifact validation", "portfolio_retrain_bc_improved/artifact_validation.csv"),
    ("Auto report", "portfolio_retrain_bc_improved/portfolio_summary.md"),
    ("Performance comparison figure", "portfolio_retrain_bc_improved/report_steps_comparison.svg"),
    ("Training loss figure", "portfolio_retrain_bc_improved/report_training_loss.svg"),
    ("Rollout selection figure", "portfolio_retrain_bc_improved/report_rollout_selection.svg"),
    ("Stability diagnostics figure", "portfolio_retrain_bc_improved/report_stability_diagnostics.svg"),
    ("Robustness sweep figure", "portfolio_retrain_bc_improved/report_robustness_sweep.svg"),
]


def read_first_row(path):
    with open(path, "r", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    return rows[0] if rows else {}


def read_rows(path):
    with open(path, "r", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def as_float(row, key, default=0.0):
    try:
        return float(row.get(key, default))
    except (TypeError, ValueError):
        return default


def file_size(path):
    if not os.path.exists(path):
        return "missing"
    size = os.path.getsize(path)
    if size >= 1024 * 1024:
        return f"{size / 1024 / 1024:.1f} MB"
    if size >= 1024:
        return f"{size / 1024:.1f} KB"
    return f"{size} B"


def artifact_table():
    lines = ["| Artifact | Path | Size |", "| --- | --- | ---: |"]
    for name, path in ARTIFACTS:
        lines.append(f"| {name} | `{path}` | {file_size(path)} |")
    return lines


def build_results():
    main = read_first_row("portfolio_retrain_bc_improved/bc_improved_summary.csv")
    stability = read_first_row("portfolio_retrain_bc_improved/stability_summary.csv")
    robustness_rows = read_rows("portfolio_retrain_bc_improved/robustness_summary.csv")
    validation_rows = read_rows("portfolio_retrain_bc_improved/artifact_validation.csv")
    raw_robustness = next((row for row in robustness_rows if row.get("smoothing") == "0.0"), {})
    passed = sum(1 for row in validation_rows if row.get("ok") == "True")

    lines = [
        "# Results Index",
        "",
        "This file is generated by `portfolio_generate_results_index.py` and summarizes the committed portfolio artifacts.",
        "",
        "## Headline Metrics",
        "",
        "| Metric | Value |",
        "| --- | ---: |",
        f"| Main average steps | {as_float(main, 'avg_steps'):.1f} |",
        f"| Main best steps | {as_float(main, 'best_steps'):.0f} |",
        f"| Main average reward | {as_float(main, 'avg_reward'):.2f} |",
        f"| Stability diagnostic average steps | {as_float(stability, 'avg_steps'):.1f} |",
        f"| Raw-action robustness average steps | {as_float(raw_robustness, 'avg_steps'):.1f} |",
        f"| Raw-action robustness success rate | {as_float(raw_robustness, 'success_rate'):.2%} |",
        f"| Artifact validation | {passed}/{len(validation_rows)} passed |",
        "",
        "## Visual Summary",
        "",
        "![Improved BC keyframes](portfolio_retrain_bc_improved/keyframes/bc_improved_keyframes.png)",
        "",
        "![Performance comparison](portfolio_retrain_bc_improved/report_steps_comparison.svg)",
        "",
        "## Artifact Inventory",
        "",
        *artifact_table(),
        "",
        "## Interpretation",
        "",
        "- The final result should be interpreted as an improved imitation-learning controller with long-horizon walking episodes, not a fully solved humanoid locomotion system.",
        "- Closed-loop MuJoCo rollout selection is the key practical improvement over validation-loss-only checkpoint selection.",
        "- Naive deployment-time action smoothing reduces performance in the current controller and should be moved into training objectives or reward design if needed.",
    ]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", default="RESULTS.md")
    args = parser.parse_args()
    with open(args.output, "w", encoding="utf-8") as f:
        f.write(build_results())
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
